#!/usr/bin/env python3
"""The boot loader's fonts: B310E OS's ui/font_montserrat.c cut to ASCII.

Since 2026-11-17 the OS's 9, 10 and 12 px fonts hold 484 glyphs each
(Latin-1, Latin Extended-A, Cyrillic, signs: os/tools/mkfont.py); linked
whole, the boot loader overflowed its 64 KB of NOR by some 18 KB. The menu
draws only ASCII (a card name outside it draws as '?', as with v1.20's
ASCII fonts), so this keeps each font's glyphs below U+0080 and the bits
they use, with the same names: the pixels of every ASCII glyph are the
OS's own. The glyphs are sorted by code and ASCII comes first in the bits
(mkfont.py), which is checked.

  python mkfont-ascii.py ../os/ui/font_montserrat.c OUT.c

SPDX-License-Identifier: GPL-2.0-or-later (the output stays under the OFL)
"""
import re
import sys

BITS = re.compile(r'^static const uint8_t (\w+)_bits\[(\d+)\] = \{$')
GLYPHS = re.compile(r'^static const font_glyph_t (\w+)_glyphs\[(\d+)\] = \{$')
GLYPH = re.compile(r'^\s*\{ 0x([0-9a-f]{4}),\s*(\d+),\s*(\d+),\s*(\d+),\s*(-?\d+),\s*(-?\d+),\s*(\d+) \},$')
FONT = re.compile(r'^const font_t font_(\w+) = \{ (\d+), (\d+), (\d+), (\w+)_glyphs, (\w+)_bits \};$')


def main(src, out):
    lines = open(src, encoding='utf-8').read().split('\n')
    head, fonts, order = [], {}, []
    i = 0
    while i < len(lines) and not BITS.match(lines[i]):
        head.append(lines[i])
        i += 1
    while i < len(lines):
        line = lines[i]
        m = BITS.match(line)
        if m:
            name, data = m.group(1), []
            i += 1
            while lines[i] != '};':
                data += [b.strip() for b in lines[i].split(',') if b.strip()]
                i += 1
            assert len(data) == int(m.group(2)), name
            fonts.setdefault(name, {})['bits'] = data
            order.append(name)
        m = GLYPHS.match(line)
        if m:
            name, glyphs = m.group(1), []
            i += 1
            while lines[i] != '};':
                g = GLYPH.match(lines[i])
                assert g, lines[i]
                glyphs.append((lines[i], [int(g.group(1), 16)] + [int(v) for v in g.groups()[1:]]))
                i += 1
            assert len(glyphs) == int(m.group(2)), name
            fonts[name]['glyphs'] = glyphs
        m = FONT.match(line)
        if m:
            fonts[m.group(1)]['font'] = m.groups()
        i += 1
    body = head
    for name in order:
        f = fonts[name]
        keep = [g for g in f['glyphs'] if g[1][0] < 0x80]
        codes = [g[1][0] for g in f['glyphs']]
        assert codes == sorted(codes), f'{name}: glyphs not sorted'
        assert keep == f['glyphs'][:len(keep)], f'{name}: ASCII not first'
        cut = max(g[1][1] + (g[1][2] + 1) // 2 * g[1][3] for g in keep)
        rest = f['glyphs'][len(keep):]
        assert all(g[1][1] >= cut for g in rest), f'{name}: ASCII bits not first'
        bits = f['bits'][:cut]
        body.append(f'static const uint8_t {name}_bits[{len(bits)}] = {{')
        for j in range(0, len(bits), 16):
            body.append('    ' + ', '.join(bits[j:j + 16]) + ',')
        body.append('};')
        body.append(f'static const font_glyph_t {name}_glyphs[{len(keep)}] = {{')
        body += [g[0] for g in keep]
        body.append('};')
        _, asc, desc, _, _, _ = f['font']
        body.append(f'const font_t font_{name} = {{ {asc}, {desc}, {len(keep)}, '
                    f'{name}_glyphs, {name}_bits }};')
        body.append('')
    with open(out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('/* Generated by boot/mkfont-ascii.py from os/ui/font_montserrat.c:\n'
                 ' * its glyphs below U+0080 only. Do not edit. */\n')
        fh.write('\n'.join(body))


if __name__ == '__main__':
    main(*sys.argv[1:3])
